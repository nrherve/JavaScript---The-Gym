let grade = "B";
switch (grade){
    case "A":
        console.log("Excellent!");
        break;
    case "B":
        console.log("Good job!");
        break;
    case "C":
        console.log("You can do better!");
        break;
    case "D":
        console.log("You need to work harder!");
        break;
    case "F":
        console.log("You failed!");
        break;
    default:
        console.log("Invalid grade");
}
